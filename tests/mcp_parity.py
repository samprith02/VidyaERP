FAC = faculty_with_plans(DATE, 4)
assert len(FAC) >= 4, f"need 4 faculty teaching on {DATE}, found {len(FAC)}"
PENDING_REQ = one(con, "SELECT id FROM requests WHERE status='Pending' ORDER BY id LIMIT 1")["id"]


