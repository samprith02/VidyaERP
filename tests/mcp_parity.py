def check(name, cond, detail=""):
    global PASSED
    if cond:
        PASSED += 1
        print(f"  ok   {name}")
    else:
        FAILED.append(f"{name} :: {detail}")
        print(f"  FAIL {name}  {detail}")


con = db.connect()


# ===================================================================== helpers
def fresh_session():
    """Each path is a separate client, so each gets its own session."""
    return {"pending": None, "history": [], "ctx": {}}


def counts():
    return {
        "overrides": one(con, "SELECT COUNT(*) c FROM overrides WHERE status='Applied'")["c"],
        "notifications": one(con, "SELECT COUNT(*) c FROM notifications")["c"],
        "requests": one(con, "SELECT COUNT(*) c FROM requests")["c"],
        "pending_requests": one(con, "SELECT COUNT(*) c FROM requests WHERE status='Pending'")["c"],
        "timetable": one(con, "SELECT COUNT(*) c FROM timetable")["c"],
    }


def verdict(result):
    """The one thing every path must agree on."""
    d = result.get("data") or {}
    if not isinstance(d, dict):
        return "ok"
    if "BLOCKED" in d:
        return "blocked"
    if "error" in d:
        return "error"
    # broadcast_notice refuses by returning an unsent draft rather than a
    # BLOCKED key. Same refusal, different shape -- classify it as one.
    if str(d.get("status", "")).startswith("NOT SENT"):
        return "blocked"
    return "ok"


def unwrap(response):
    """A tools/call JSON-RPC response back to the {data, trace} a tool returned."""
    payload = json.loads(response["result"]["content"][0]["text"])
    return {"data": payload.get("data", {}), "trace": payload.get("trace", []),
            "isError": response["result"].get("isError")}


def run_path(path, S, name, args, approves):
    """Drive one tool call down one of the three paths.

    `approves` is what the ADMIN did, not what the model claims. On the web path
    that is the admin's typed message; over MCP it is a code the admin minted.
    The model's own arguments are handed over untouched either way -- that is
    the point of the exercise.
    """
    args = dict(args)
    if path == "internal_planner":
        U = "yes, apply it" if approves else "show me the options first"
        return tools.execute(con, S, U, name, args)

    if approves:                       # the admin minted a code and read it out
        args["approval_code"] = mcp_server.mint_approval(con)["code"]

    if path == "mcp_call_as":
        U = mcp_server.approval_text(con, name, args)
        return mcp_server.call_as(con, S, U, name, args)

    if path == "mcp_jsonrpc":
        resp = mcp_server.handle_request(
            {"jsonrpc": "2.0", "id": 1, "method": "tools/call",
             "params": {"name": name, "arguments": args}}, con, S)
        return unwrap(resp)

    raise AssertionError(f"unknown path {path}")


PATHS = ("internal_planner", "mcp_call_as", "mcp_jsonrpc")


def propose_coverage(S, faculty_name, date):
    return tools.execute(con, S, "who covers for them?", "plan_absence_coverage",
                         {"faculty_name": faculty_name, "date": date})


def faculty_with_plans(date, want):
    """Faculty who actually have classes on `date`, so a proposal exists to
    commit. The allowed-write control needs a DIFFERENT one per path: committing
    the same absence three times would have the second and third path writing
    over the first path's overrides, which would look like a divergence and be
    nothing of the kind."""
    found = []
    busy = [r["name"] for r in con.execute(
        """SELECT f.name, COUNT(t.id) load FROM faculty f JOIN timetable t ON t.faculty=f.id
           GROUP BY f.id ORDER BY load DESC LIMIT 40""")]
    for nm in busy:
        S = fresh_session()
        if (propose_coverage(S, nm, date).get("data") or {}).get("plans"):
            found.append(nm)
            if len(found) == want:
                break
    return found


NEXT_WORKDAY = next(TODAY + dt.timedelta(days=i) for i in range(1, 8)
                    if day_of(TODAY + dt.timedelta(days=i)) != "Sun")
