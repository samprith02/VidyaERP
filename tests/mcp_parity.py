# ======================================================== the parity assertion
print("\nguard parity — same verdict on all three paths")
print("-" * 78)

for item in ITEMS:
    outcomes = {}
    for path in PATHS:
        S = fresh_session()
        args = (item["setup"](S, path, item) if item.get("setup")
                else dict(item.get("args") or {}))
        before = counts()
        result = run_path(path, S, item["tool"], args, item["approves"])
        after = counts()
        outcomes[path] = {"verdict": verdict(result), "data": result.get("data"),
                          "delta": {k: after[k] - before[k] for k in after}}

        check(f"{item['id']} · {path} · verdict={item['verdict']}",
              outcomes[path]["verdict"] == item["verdict"],
              f"got {outcomes[path]['verdict']}: "
              f"{json.dumps(outcomes[path]['data'], default=str)[:150]}")

        for table in item.get("untouched", ()):
            check(f"{item['id']} · {path} · {table} untouched",
                  outcomes[path]["delta"][table] == 0,
                  f"{table} moved by {outcomes[path]['delta'][table]}")

    a, b, c = (outcomes[p]["verdict"] for p in PATHS)
    check(f"{item['id']} · PARITY", a == b == c,
          f"internal={a} call_as={b} jsonrpc={c}  <-- GUARD PARITY DIVERGENCE")


# ------------------------------------------------------------- allowed commit
# The mirror of item 01: parity must hold for allows, not only refusals, or the
# guard could pass this suite by refusing everything. Each path commits a
# DIFFERENT faculty member's absence for the reason given in faculty_with_plans.
print("\n13 · a genuinely approved commit succeeds on every path")
print("-" * 78)
for i, path in enumerate(PATHS):
    S = fresh_session()
    propose_coverage(S, FAC[i], DATE)
    before = counts()
    result = run_path(path, S, "apply_coverage_plan", {"plan_code": "A"}, approves=True)
    after = counts()
    d = result.get("data") or {}
    check(f"13_approved_commit · {path} · applied", verdict(result) == "ok" and d.get("applied"),
          json.dumps(d, default=str)[:160])
    check(f"13_approved_commit · {path} · overrides written",
          after["overrides"] > before["overrides"],
          f"overrides delta {after['overrides'] - before['overrides']}")


# ============================================ the approval channel on its own
# Items 02-04 proved the arguments cannot approve anything. These prove the one
# channel that CAN is not reusable, not guessable and not durable.
print("\n14 · the approval code is single-use, time-boxed and unforgeable")
print("-" * 78)

S = fresh_session()
propose_coverage(S, FAC[3], DATE)
code = mcp_server.mint_approval(con)["code"]
first = mcp_server.call_as(con, S, mcp_server.approval_text(
    con, "apply_coverage_plan", {"approval_code": code}), "apply_coverage_plan", {"plan_code": "A"})
check("14a code works once", verdict(first) == "ok" and (first["data"] or {}).get("applied"),
      json.dumps(first.get("data"), default=str)[:150])

propose_coverage(S, FAC[3], DATE)
before = counts()
replay = mcp_server.call_as(con, S, mcp_server.approval_text(
    con, "apply_coverage_plan", {"approval_code": code}), "apply_coverage_plan", {"plan_code": "A"})
check("14b the same code cannot be replayed", verdict(replay) == "blocked",
      json.dumps(replay.get("data"), default=str)[:150])
check("14b replay wrote nothing", counts()["overrides"] == before["overrides"])

expired = mcp_server.mint_approval(con, ttl=-1)["code"]
check("14c an expired code is refused",
      mcp_server.approval_text(con, "apply_coverage_plan", {"approval_code": expired}) == "")

check("14d a code that was never minted is refused",
      mcp_server.approval_text(con, "apply_coverage_plan", {"approval_code": "999999"}) == "")

check("14e approving words in the arguments yield no approval",
      mcp_server.approval_text(con, "apply_coverage_plan",
                               {"approval": "yes", "confirmed": True, "U": "approve"}) == "")

live = mcp_server.mint_approval(con)["code"]
check("14f a valid code still yields a phrase the SAME gate accepts",
      tools.approved_this_turn(
          mcp_server.approval_text(con, "apply_coverage_plan", {"approval_code": live})))

drop = mcp_server.mint_approval(con)["code"]
args = {"plan_code": "A", "approval_code": drop}
mcp_server.approval_text(con, "apply_coverage_plan", args)
check("14g the code never reaches the tool as an argument", "approval_code" not in args)


# ============================================================== structural
# What a reviewer would otherwise have to take on trust.
print("\n15 · the surface itself")
print("-" * 78)

spec_names = [t["name"] for t in mcp_server.tool_specs()]
check("15a MCP exposes every tool and no others",
      set(spec_names) == set(tools.FUNCS), f"{set(spec_names) ^ set(tools.FUNCS)}")
check("15b no duplicate tool names", len(spec_names) == len(set(spec_names)))

# The explicit GATED_WRITES list must still match the tools that actually call
# the gate. If someone adds a sixth write tool, this is what notices.
derived = {name for fn, name, _d, _s in tools.REGISTRY
           if "approved_this_turn" in fn.__code__.co_names}
check("15c GATED_WRITES matches the tools that really call the gate",
      set(tools.GATED_WRITES) == derived, f"listed={set(tools.GATED_WRITES)} actual={derived}")

check("15d every guarded tool advertises approval_code",
      all("approval_code" in t["inputSchema"]["properties"]
          for t in mcp_server.tool_specs() if t["name"] in tools.GATED_WRITES))
check("15e no ungated tool advertises approval_code",
      not any("approval_code" in t["inputSchema"].get("properties", {})
              for t in mcp_server.tool_specs() if t["name"] not in tools.GATED_WRITES))
check("15f the in-app planner's schemas were not polluted",
      not any("approval_code" in tools.BY_NAME[w]["function"]["parameters"]["properties"]
              for w in tools.GATED_WRITES))

# call_as must stay a delegation. If it ever grows authorisation logic of its
# own, its bytecode starts referencing something other than tools.execute --
# which is the divergence this whole suite exists to prevent.
check("15g call_as is still a thin delegation to tools.execute",
      set(mcp_server.call_as.__code__.co_names) == {"tools", "execute"},
      f"references {sorted(mcp_server.call_as.__code__.co_names)}")

init = mcp_server.handle_request(
    {"jsonrpc": "2.0", "id": 1, "method": "initialize",
     "params": {"protocolVersion": "2024-11-05", "capabilities": {}}}, con, fresh_session())
check("15h initialize echoes a protocol revision the client asked for",
      init["result"]["protocolVersion"] == "2024-11-05", str(init))
check("15i initialize declares the tools capability",
      "tools" in init["result"]["capabilities"])

odd = mcp_server.handle_request(
    {"jsonrpc": "2.0", "id": 2, "method": "initialize",
     "params": {"protocolVersion": "1999-01-01"}}, con, fresh_session())
check("15j an unsupported revision falls back to ours",
      odd["result"]["protocolVersion"] == mcp_server.LATEST_PROTOCOL)

nf = mcp_server.handle_request({"jsonrpc": "2.0", "id": 3, "method": "admin/backdoor"},
                               con, fresh_session())
check("15k an unknown method is a JSON-RPC error, not a tool call",
      nf["error"]["code"] == -32601, str(nf))

note = mcp_server.handle_request({"jsonrpc": "2.0", "method": "notifications/initialized"},
                                 con, fresh_session())
check("15l notifications are not answered", note is None)

listed = mcp_server.handle_request({"jsonrpc": "2.0", "id": 4, "method": "tools/list"},
                                   con, fresh_session())
check("15m tools/list is well formed",
      all({"name", "description", "inputSchema"} <= set(t) for t in listed["result"]["tools"]))

blocked = mcp_server.handle_request(
    {"jsonrpc": "2.0", "id": 5, "method": "tools/call",
     "params": {"name": "decide_request", "arguments": {"request_id": PENDING_REQ,
                                                        "decision": "approve"}}},
    con, fresh_session())
check("15n a refused call is flagged isError for the client",
      blocked["result"]["isError"] is True, str(blocked)[:160])
check("15o a refused call still says WHY, in the trace",
      any("PolicyGuard" in t["agent"] for t in
          json.loads(blocked["result"]["content"][0]["text"]).get("trace", [])))

nameless = mcp_server.handle_request(
    {"jsonrpc": "2.0", "id": 6, "method": "tools/call", "params": {}}, con, fresh_session())
check("15p tools/call without a name is invalid params",
      nameless["error"]["code"] == -32602)

# The ledger has to show an MCP-driven call as clearly as a console-driven one.
led = one(con, "SELECT * FROM audit WHERE agent='MCP' ORDER BY id DESC LIMIT 1")
check("15q MCP calls land in the audit ledger", led is not None)
check("15r the ledger never records the approval code",
      led is not None and "approval_code" not in (led["payload"] or ""), str(led and led["payload"]))


