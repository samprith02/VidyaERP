"""MCP guard parity. No server, no LLM, no API cost.

    python tests/mcp_parity.py

Runs against a COPY of college.db in the system temp directory, so it can never
damage the shipped database.

--------------------------------------------------------------------------
The claim under test, stated precisely
--------------------------------------------------------------------------

    A guard verdict is identical regardless of which model drives the tools,
    including one we do not control.

VidyaERP has two entry points to its capabilities:

    the app's own planner   ->  llm_agent.py       -> tools.execute
    an external MCP client  ->  mcp_server.py      -> tools.execute

Both MUST reach the tools through the same gate, so an external LLM gets no
authority the in-app planner lacks. `mcp_server.call_as` is, by reading, a thin
delegation straight to `tools.execute` -- so this suite is also a regression
guard: if a future change ever gives the MCP path its own approval logic, this
file is what catches the divergence.

--------------------------------------------------------------------------
What is different here from MAWOS's parity suite, and why it matters more
--------------------------------------------------------------------------
MAWOS gated on ROLE, which is an attribute of the caller and is the same on
both paths by construction. VidyaERP gates on APPROVAL IN THE CURRENT TURN --
`tools.approved_this_turn(U)`, where `U` is the admin's own message. On the web
path the model cannot forge `U` because it never writes the user's message.

Over MCP there is no user message: the caller IS the model. So the sharp
question, which has no MAWOS analogue, is whether a model can talk its own
approval into existence -- by putting approving words in the arguments, by
inventing a code, by replaying a spent one, or by colliding with the `U`
parameter itself. Items 02-04 and 13-15 are that question.

Three paths are replayed per item, not two:

    internal_planner  tools.execute(...)               what llm_agent.py calls
    mcp_call_as       mcp_server.call_as(...)          the delegation layer
    mcp_jsonrpc       a real tools/call round trip     the transport, where a
                                                       forged approval would
                                                       actually be built

The third is the one that earns its keep. `call_as` cannot forge an approval
because it is handed one; the JSON-RPC handler is where `U` is constructed from
whatever the client sent, so that is where the bypass would live.

If any item ever diverges between paths, that is a real finding. Report it --
do not edit this file to make it pass again.
"""
