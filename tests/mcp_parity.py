# Each item: what is called, whether the ADMIN approved, the verdict every path
# must reach, and which table must be untouched when the verdict is a refusal.
def _plan_first(S, path, i):
    """Setup shared by every apply_coverage_plan item: a live proposal, made the
    honest way. A refused commit leaves it pending, so one proposal per path is
    enough for the refusal items."""
    propose_coverage(S, FAC[0], DATE)
    return {"plan_code": "A"}


